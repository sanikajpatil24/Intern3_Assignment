# Step 1: Take marks from the user
marks = int(input())

# Step 2: Convert marks out of 100 to out of 20
out_of_20 = marks / 100 * 20

# Step 3: Calculate 15 percent weightage
weightage = marks * 15 / 100

# Step 4: Display the results
print(f"Marks: {marks}")
print(f"Out of 20: {out_of_20}")
print(f"Weightage: {weightage}")